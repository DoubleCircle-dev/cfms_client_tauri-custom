// Generated CSS prevents a theme flash before the client runtime initializes.
// Theme objects remain the single source of truth.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { lightTheme, darkTheme } from '../src/lib/fluent/theme.ts';

const path = fileURLToPath(new URL('../src/lib/fluent/theme.css', import.meta.url));
const css = '/* Generated by pnpm assets:fluent. Edit theme.ts, not this file. */\n'
  + Object.entries({ light: lightTheme, dark: darkTheme }).map(([scheme, theme]) =>
    'html[data-theme="' + scheme + '"] {\n'
    + Object.entries(theme).map(([key, value]) => '  --' + key + ': ' + value + ';').join('\n')
    + '\n}\n',
  ).join('\n')
  + '\n/* CSS inheritance reaches Fluent shadow roots; document-wide * does not. */\n'
  + 'html[data-theme][data-reduce-motion="true"] {\n'
  + Object.keys(lightTheme).filter(key => key.startsWith('duration'))
    .map(key => '  --' + key + ': 0.01ms;').join('\n')
  + '\n}\n';
if (process.argv.includes('--check')) {
  if (readFileSync(path, 'utf8') !== css) throw new Error('Fluent theme CSS is stale. Run pnpm assets:fluent.');
} else {
  writeFileSync(path, css);
}
